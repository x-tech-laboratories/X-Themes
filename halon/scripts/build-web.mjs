#!/usr/bin/env node
// Writes web/halon-tokens.css from web/_tokens.css, filling each @name with that colour from the GTK token files.
//
// Usage:
//   node scripts/build-web.mjs           # -> web/halon-tokens.css
//   node scripts/build-web.mjs --check   # fail if the output is stale

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = process.env.HALON_ROOT ?? join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

// ============================================================================
// Tokens
// ============================================================================

function load_tokens(scheme) {
  const raw = {};
  const path = join(root, `gtk/Halon/shared/_tokens-${scheme}.css`);
  for (const match of readFileSync(path, "utf8").matchAll(/@define-color\s+([\w-]+)\s+([^;]+);/g)) raw[match[1]] = match[2].trim();
  const resolve = (name, seen = new Set()) => {
    if (seen.has(name)) throw new Error(`circular token: ${name}`);
    seen.add(name);
    const value = raw[name];
    if (value === undefined) throw new Error(`web/_tokens.css names @${name}, which the ${scheme} GTK tokens do not hold`);
    return value.startsWith("@") ? resolve(value.slice(1), seen) : value;
  };
  return resolve;
}

// Fills the @names in each declaration's value from the scheme's tokens.
function fill(block, resolve) {
  return block.replace(/^(\s*--[\w-]+:)([^;]*);/gm, (_, name, value) => `${name}${value.replace(/@([\w-]+)/g, (_, token) => resolve(token))};`);
}

// ============================================================================
// Layers
// ============================================================================

// A colour literal in the component sheet would be a second palette beside the tokens.
const literal = /#[0-9a-fA-F]{3,8}\b|(?<![-\w])rgba?\(|(?<![-\w])hsla?\(/;

function audit_components(source) {
  let problems = 0;
  source.split("\n").forEach((line, index) => {
    if (!literal.test(line)) return;
    console.error(`web/halon.css:${index + 1}: colour literal outside the token layer`);
    console.error(`   ${line.trim().slice(0, 110)}`);
    problems += 1;
  });
  return problems;
}

// ============================================================================
// Write or check
// ============================================================================

const source = readFileSync(join(root, "web/_tokens.css"), "utf8");
const dark_start = source.indexOf("@media");
if (dark_start < 0) throw new Error("web/_tokens.css has no dark media query");

const header = `/* Halon tokens for the web: GENERATED by scripts/build-web.mjs from web/_tokens.css and gtk/Halon/shared/_tokens-*.css; edit those, not this. */`;
const body = source.slice(source.indexOf("*/") + 2);
const body_dark_start = body.indexOf("@media");
const contents = `${header}${fill(body.slice(0, body_dark_start), load_tokens("light"))}${fill(body.slice(body_dark_start), load_tokens("dark"))}`;

let problems = audit_components(readFileSync(join(root, "web/halon.css"), "utf8"));
const output_path = join(root, "web/halon-tokens.css");

if (check) {
  if (!existsSync(output_path) || readFileSync(output_path, "utf8") !== contents) {
    console.error("web/halon-tokens.css is stale — run: node scripts/build-web.mjs");
    problems += 1;
  } else {
    console.log("web/halon-tokens.css is up to date.");
  }
} else {
  writeFileSync(output_path, contents);
  console.log(`Wrote ${output_path}`);
}

if (!problems) console.log("No colour literals outside the token layer.");
process.exit(problems ? 1 : 0);
